def py_sample_to_r_sample(py_name):
    """
    Convert dreampy sample name to R-style donor_id_tissue_abbrev string.

    dreampy aggregate_pseudobulk with groupby=[assay, donor_id, tissue_abbrev]
    produces obs_names like "('cd3_gd', '582C', 'spl')".
    R's aggregateToPseudoBulk uses sample_id = "donor_id_tissue_abbrev", giving
    plain strings like "582C_spl".

    Extracts the last two components (donor, tissue) and joins with '_'.

    Pass-through for Perez since sample_id is pre-composed.
    """
    s = str(py_name)
    if s.startswith("("):
        parts = s.strip("()").replace("'", "").split(", ")
        return "_".join(parts[1:])
    return s


def intersect_genes(py_genes, ref_index, assay, ref_name):
    """
    Compute intersection of Python gene list with R reference index.

    Prints diagnostic if sets differ (Python extras = R convergence failures).
    Returns (shared_genes, py_indices) where:
      - shared_genes: list in Python's order, for ref.loc[shared, col]
      - py_indices: np array of ints, for fit.coefficients[py_idx, :]
    """
    r_set = set(ref_index)

    py_only = [g for g in py_genes if g not in r_set]
    r_only = [g for g in ref_index if g not in set(py_genes)]

    if py_only:
        print(
            f"  {assay} [{ref_name}]: {len(py_only)} genes in Python but not R "
            f"(R convergence failures): {py_only[:10]}"
            f"{'...' if len(py_only) > 10 else ''}"
        )
    if r_only:
        print(
            f"  {assay} [{ref_name}]: {len(r_only)} genes in R but not Python: "
            f"{r_only[:10]}{'...' if len(r_only) > 10 else ''}"
        )

    shared = [g for g in py_genes if g in r_set]
    py_idx = np.array([i for i, g in enumerate(py_genes) if g in r_set])

    assert len(shared) > 0, (
        f"{assay}: no shared genes between Python ({len(py_genes)}) "
        f"and R ({len(ref_index)})"
    )

    return shared, py_idx

