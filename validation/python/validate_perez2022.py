def validation_metrics(py_vals, r_vals, name=""):
    """Compute seven validation metrics comparing Python outputs to R reference.

    Ratio-based metrics (Python / R, ideal = 1.0):

    Mean ratio — Detects systematic bias. Values consistently above or below
    1.0 indicate a multiplicative offset (e.g., 1.05 means Python runs ~5% high).

    Median ratio — Same idea but robust to outliers. If mean and median diverge,
    a few extreme genes are pulling the mean.

    Ratio range — Worst-case spread. Tight range like [0.9999, 1.0001] means
    uniform agreement; wide range like [0.85, 1.15] means gene-specific
    discrepancies.

    Difference-based metrics:

    Mean % difference — Like mean ratio but additive and signed. Positive =
    Python systematically larger.

    Max |% difference| — Single worst gene. Important caveat: this is misleading
    for near-zero values. A t-statistic of 0.0001 vs 0.0002 is 100% relative
    difference but meaningless in practice.

    RMSE — Root mean squared absolute difference. Scale-dependent, so only
    meaningful when comparing the same metric across runs.

    Agreement metric:

    Pearson correlation — Measures linear agreement. 1.000000 means perfect
    rank-and-scale agreement. Limitation: correlation can be 1.0 even with
    systematic bias (e.g., Python = 2*R would still correlate perfectly).
    That's why we need both correlation and the ratio metrics.

    Near-zero R values (|r| < 1e-10) are excluded from ratio and relative
    difference calculations to avoid inf/nan artifacts. These are counted
    and reported.

    Returns dict of all metrics for downstream gating and paper reporting.
    """
    py = np.asarray(py_vals, dtype=np.float64).flatten()
    r = np.asarray(r_vals, dtype=np.float64).flatten()

    # Remove NaN/inf from both sides
    mask = np.isfinite(py) & np.isfinite(r)
    py, r = py[mask], r[mask]

    n = len(py)
    if n == 0:
        print(f"=== {name} === NO FINITE VALUES")
        return {"n": 0, "correlation": np.nan}

    # Correlation (always computable)
    corr = np.corrcoef(py, r)[0, 1] if n > 1 else np.nan

    # RMSE (always computable)
    diff = py - r
    rmse = np.sqrt(np.mean(diff ** 2))

    # Ratio and rel_diff: mask near-zero denominators to avoid inf
    denom_ok = np.abs(r) > 1e-10
    n_denom_excluded = n - denom_ok.sum()
    if denom_ok.sum() > 0:
        ratio = py[denom_ok] / r[denom_ok]
        rel_diff = (py[denom_ok] - r[denom_ok]) / r[denom_ok] * 100
        mean_ratio = np.mean(ratio)
        median_ratio = np.median(ratio)
        ratio_min = np.min(ratio)
        ratio_max = np.max(ratio)
        mean_pct_diff = np.mean(rel_diff)
        max_abs_pct_diff = np.max(np.abs(rel_diff))
    else:
        mean_ratio = median_ratio = ratio_min = ratio_max = np.nan
        mean_pct_diff = max_abs_pct_diff = np.nan

    print(f"=== {name} ===")
    print(f"  N: {n}" + (f" ({n_denom_excluded} near-zero excluded from ratios)"
                         if n_denom_excluded > 0 else ""))
    print(f"  Mean ratio (Py/R):     {mean_ratio:.6f}  (ideal: 1.0)")
    print(f"  Median ratio:          {median_ratio:.6f}")
    print(f"  Ratio range:           [{ratio_min:.6f}, {ratio_max:.6f}]")
    print(f"  Mean % difference:     {mean_pct_diff:+.4f}%")
    print(f"  Max |% difference|:    {max_abs_pct_diff:.4f}%")
    print(f"  RMSE:                  {rmse:.6f}")
    print(f"  Correlation:           {corr:.6f}")

    return {
        "n": n,
        "mean_ratio": mean_ratio,
        "median_ratio": median_ratio,
        "ratio_min": ratio_min,
        "ratio_max": ratio_max,
        "mean_pct_diff": mean_pct_diff,
        "max_abs_pct_diff": max_abs_pct_diff,
        "rmse": rmse,
        "correlation": corr,
    }

def assert_agreement(py_vals, r_vals, name="",
                     corr_min=None, atol=None, frac_max=None,
                     assay="", quantity="", coef="",
                     n_samples=0, n_genes_total=0, n_genes_shared=0):
    """
    Report validation_metrics, log to METRICS_LOG, then apply pass/fail gates.

    Gates (all optional — omit or set to None for report-only):
      corr_min: Pearson correlation floor. Fail if corr < corr_min.
      atol + frac_max: Fraction of elements with |py - r| > atol must be
                       <= frac_max. Both must be specified together.

    Metadata for CSV:
      assay, quantity, coef: identify the comparison
      n_samples, n_genes_total, n_genes_shared: assay dimensions

    Returns the metrics dict for further inspection.
    """
    m = validation_metrics(py_vals, r_vals, name=name)

    if m["n"] == 0:
        pytest.fail(f"{name}: no finite values to compare")

    # --- Compute fraction gate upfront (before any assertions) ---
    frac_exceed = None
    if atol is not None and frac_max is not None:
        py = np.asarray(py_vals, dtype=np.float64).flatten()
        r = np.asarray(r_vals, dtype=np.float64).flatten()
        finite = np.isfinite(py) & np.isfinite(r)
        py_f, r_f = py[finite], r[finite]
        n_exceed = np.sum(np.abs(py_f - r_f) > atol)
        frac_exceed = n_exceed / len(py_f) if len(py_f) > 0 else 0.0
        print(f"  Fraction > atol={atol}: {n_exceed}/{len(py_f)} "
              f"({frac_exceed:.4%}) [max: {frac_max:.1%}]")

    # --- Determine pass/fail before asserting ---
    passed = True
    gate = ""
    if corr_min is not None and m["correlation"] < corr_min:
        passed = False
        gate = f"corr {m['correlation']:.6f} < {corr_min}"
    if frac_exceed is not None and frac_exceed > frac_max:
        passed = False
        if gate:
            gate += "; "
        gate += f"frac {frac_exceed:.4%} > {frac_max:.1%}"

    # --- Log to METRICS_LOG ---
    METRICS_LOG.append({
        "assay": assay,
        "n_samples": n_samples,
        "n_genes_total": n_genes_total,
        "n_genes_shared": n_genes_shared,
        "quantity": quantity,
        "coefficient": coef,
        "n_compared": m["n"],
        "mean_ratio": m.get("mean_ratio", np.nan),
        "median_ratio": m.get("median_ratio", np.nan),
        "ratio_min": m.get("ratio_min", np.nan),
        "ratio_max": m.get("ratio_max", np.nan),
        "mean_pct_diff": m.get("mean_pct_diff", np.nan),
        "max_abs_pct_diff": m.get("max_abs_pct_diff", np.nan),
        "rmse": m.get("rmse", np.nan),
        "correlation": m.get("correlation", np.nan),
        "frac_exceed": frac_exceed if frac_exceed is not None else "",
        "corr_min": corr_min if corr_min is not None else "",
        "atol": atol if atol is not None else "",
        "frac_max": frac_max if frac_max is not None else "",
        "gate": gate,
        "passed": passed,
    })

    # --- Now assert (correlation first, then fraction) ---
    if corr_min is not None:
        assert m["correlation"] >= corr_min, (
            f"{name}: correlation {m['correlation']:.6f} < {corr_min}"
        )

    if atol is not None and frac_max is not None:
        assert frac_exceed <= frac_max, (
            f"{name}: {frac_exceed:.4%} of elements exceed atol={atol} "
            f"(max allowed: {frac_max:.1%})"
        )

    return m

