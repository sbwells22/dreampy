    @pytest.mark.parametrize("assay", ASSAYS)
    def test_fit_no_catastrophic_failures(self, pipeline, assay):
        """
        Allow boundary convergence, flag only hard failures.
        For real data, some genes may hit boundaries -- that's expected.
        Fail if > 5% of genes truly failed (not boundary).
        """
        if assay not in pipeline:
            pytest.skip(f"Assay {assay} not in pipeline results")

        from dreampy import FitStatus

        fit = pipeline[assay]["fit"]
        n_genes = len(pipeline[assay]["gene_names"])

        failed = fit.fit_status != FitStatus.SUCCESS
        boundary = fit.fit_status == FitStatus.BOUNDARY
        truly_failed = failed & ~boundary
        n_failed = truly_failed.sum()

        threshold = max(1, int(0.05 * n_genes))
        if n_failed > threshold:
            failed_genes = np.array(pipeline[assay]["gene_names"])[truly_failed]
            pytest.fail(
                f"{assay}: {n_failed}/{n_genes} genes failed (>{threshold} threshold). "
                f"First 10: {list(failed_genes[:10])}"
            )

