    ad = sc.read_h5ad(INPUT_H5AD)

    # --- Step 0: Pseudobulk aggregation ---
    pb = dp.aggregate_pseudobulk(ad, groupby=GROUPBY)

    # =====================================================================
    #  Preprocessing: filter_samples -> TMM -> filter -> log2CPM -> voom
    # =====================================================================

    import time
    t0_preproc = time.perf_counter()

    pb = dp.filter_samples(pb, min_cells=MIN_CELLS, min_samples=MIN_SAMPLES)
    pb = dp.compute_tmm_factors(pb, assay_col="assays")

    all_gene_names = list(pb.var_names)

    assays_dict = dp.filter_by_expr(
        pb, assay_col="assays", min_count=MIN_COUNT, min_prop=MIN_PROP
    )

    results = {"_all_gene_names": all_gene_names}

    for assay_name, assay_pb in assays_dict.items():
        rec = {}
        rec["sample_names"] = list(assay_pb.obs_names)
        rec["r_sample_names"] = [
            py_sample_to_r_sample(s) for s in assay_pb.obs_names
        ]
        rec["kept_genes"] = list(assay_pb.var_names)

        assert "norm_factors" in assay_pb.obs.columns, (
            f"{assay_name}: norm_factors missing from .obs after filter_by_expr"
        )
        assert "lib_size" in assay_pb.obs.columns, (
            f"{assay_name}: lib_size missing from .obs after filter_by_expr"
        )

        rec["norm_factors"] = assay_pb.obs["norm_factors"].values.copy()
        rec["lib_size"] = assay_pb.obs["lib_size"].values.copy()

        assay_pb = dp.log2cpm(assay_pb)
        rec["log2cpm"] = assay_pb.X.copy()

        assay_pb = dp.estimate_weights(
            assay_pb, formula=FORMULA, reml=False, n_jobs=-1, span=0.5
        )
        assert "weights" in assay_pb.layers, (
            f"{assay_name}: weights layer missing after estimate_weights"
        )
        rec["weights"] = assay_pb.layers["weights"].copy()
        rec["_assay_pb"] = assay_pb
        results[assay_name] = rec

    t_preproc = time.perf_counter() - t0_preproc
    n_assays = len([k for k in results if not k.startswith("_")])
    print(
        f"\n╔══ Preprocessing ══╗\n"
        f"║  {n_assays} assays: filter_samples -> estimate_weights\n"
        f"║  {t_preproc:.1f} sec total\n"
        f"╚═══════════════════╝"
    )

    # =====================================================================
    #  Model fitting: fit_models (Satterthwaite) -> eBayes
    # =====================================================================

    t0_fitting = time.perf_counter()
    assay_timings = {}

    for assay_name in [k for k in results if not k.startswith("_")]:
        rec = results[assay_name]
        assay_pb = rec.pop("_assay_pb")

        t0_assay = time.perf_counter()

        fit = dp.fit_models(
            assay_pb,
            formula=FORMULA,
            n_jobs=-1,
            reml=True,
            assay_name=assay_name,
            ddf="Satterthwaite",
        )
        rec["fit"] = fit

        fit_eb = dp.ebayes(fit)
        rec["fit_eb"] = fit_eb
        rec["gene_names"] = list(assay_pb.var_names)

        t_assay = time.perf_counter() - t0_assay
        assay_timings[assay_name] = t_assay
        n_genes = len(rec["gene_names"])
        print(f"  {assay_name}: {n_genes} genes, {t_assay:.1f} sec")

        results_table = dp.get_results(fit_eb, assay_name=assay_name)
        results_table.to_csv(REF_DIR / f"{assay_name}_py_results.csv")

        _save_py_outputs(assay_name, rec, all_gene_names, REF_DIR)

    t_fitting = time.perf_counter() - t0_fitting
    print(
        f"\n╔══ Model fitting ══╗\n"
        f"║  {n_assays} assays: fit_models -> eBayes\n"
        f"║  {t_fitting:.1f} sec total\n"
        f"╚═══════════════════╝"
    )

    # -- Write timing file --
    from datetime import datetime
    timestamp = datetime.now().strftime("%d%b%Y_%H%M%S")
    timing_path = REF_DIR / f"py_perez2022_timing_{timestamp}.txt"
    try:
        timing_lines = [
            f"preprocessing: {t_preproc:.1f} sec",
            f"model_fitting: {t_fitting:.1f} sec",
            f"total: {t_preproc + t_fitting:.1f} sec",
            f"n_assays: {n_assays}",
            "",
            "per_assay_fitting:",
        ]
        for aname, t_a in assay_timings.items():
            n_genes = len(results[aname]["gene_names"])
            timing_lines.append(f"  {aname}: {n_genes} genes, {t_a:.1f} sec")
        timing_lines.append(f"\ntimestamp: {datetime.now().isoformat()}")

        timing_path.write_text("\n".join(timing_lines))
        print(f"Timing written to: {timing_path}")
    except OSError as e:
        print(f"WARNING: Could not write timing file: {e}")

    # --- Yield results, write CSV on teardown ---
    yield results

    _write_metrics_csv()


