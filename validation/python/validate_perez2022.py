def _save_py_outputs(assay_name, rec, all_gene_names, ref_dir):
    """
    Save all intermediate pipeline quantities for one assay.

    Produces files that structurally mirror the R reference CSVs:
      {assay}_py_tmm_factors.csv     — sample-level normalization
      {assay}_py_filter_mask.csv     — per-gene keep/drop (full gene list)
      {assay}_py_log2cpm.csv         — gene x sample log2CPM matrix
      {assay}_py_voom_weights.csv    — gene x sample voom weight matrix
      {assay}_py_lmer.csv            — coefficients, SEs, sigma, varComp, rdf
      {assay}_py_satterthwaite.csv   — per-coefficient denominator df
      {assay}_py_ebayes.csv          — eBayes outputs (s2_prior/post, t, p, B)

    Column names match R reference CSVs exactly so files can be diffed or
    loaded side-by-side without translation.
    """
    from scipy.stats import false_discovery_control

    fit = rec["fit"]
    fit_eb = rec["fit_eb"]
    genes = rec["gene_names"]
    r_samples = rec["r_sample_names"]
    kept_set = set(rec["kept_genes"])
    prefix = ref_dir / f"{assay_name}_py"

    n_files = 0

    try:
        # ---- 1. TMM factors (sample-level) ----
        tmm_df = pd.DataFrame({
            "sample_id": r_samples,
            "norm_factors": rec["norm_factors"],
            "lib_size": rec["lib_size"],
            "effective_lib_size": rec["lib_size"] * rec["norm_factors"],
        })
        tmm_df.to_csv(f"{prefix}_tmm_factors.csv", index=False)
        n_files += 1

        # ---- 2. Filter mask (full gene list) ----
        filter_df = pd.DataFrame({
            "gene": all_gene_names,
            "keep": [g in kept_set for g in all_gene_names],
        })
        filter_df.to_csv(f"{prefix}_filter_mask.csv", index=False)
        n_files += 1

        # ---- 3. log2CPM matrix (gene x sample) ----
        log2cpm_df = pd.DataFrame(
            rec["log2cpm"].T,      # stored as samples x genes, transpose
            index=genes,
            columns=r_samples,
        )
        log2cpm_df.index.name = "gene"
        log2cpm_df.to_csv(f"{prefix}_log2cpm.csv")
        n_files += 1

        # ---- 4. Voom weights (gene x sample) ----
        weights_df = pd.DataFrame(
            rec["weights"].T,      # same transpose
            index=genes,
            columns=r_samples,
        )
        weights_df.index.name = "gene"
        weights_df.to_csv(f"{prefix}_voom_weights.csv")
        n_files += 1

        # ---- 5. lmer-level quantities (gene x columns) ----
        lmer_data = {"gene": genes}

        for i, coef_name in enumerate(fit.coef_names):
            r_name = COEF_MAP.get(coef_name, coef_name)
            lmer_data[f"coef_{r_name}"] = fit.coefficients[:, i]
            lmer_data[f"stdev_unscaled_{r_name}"] = fit.stdev_unscaled[:, i]

        lmer_data["sigma"] = fit.sigma

        # Variance components: back-convert from theta to varComp
        # theta = sqrt(varComp) / sigma  =>  varComp = (theta * sigma)**2
        for re_name in ["donor_id", "Processing_Cohort"]:
            if re_name in fit.theta:
                theta_vec = fit.theta[re_name]
                lmer_data[f"varComp_{re_name}"] = (theta_vec * fit.sigma) ** 2
            else:
                # RE dropped (e.g., PB collinearity) — save NaN
                lmer_data[f"varComp_{re_name}"] = np.full(len(genes), np.nan)

        # Residual variance component = sigma**2
        lmer_data["varComp_resid"] = fit.sigma ** 2

        # Residual df (trace-based)
        lmer_data["rdf"] = fit.df_resid_eb

        # Effective df (if available)
        if hasattr(fit, "edf") and fit.edf is not None:
            lmer_data["edf"] = fit.edf
        else:
            lmer_data["edf"] = np.full(len(genes), np.nan)

        lmer_df = pd.DataFrame(lmer_data)
        lmer_df.to_csv(f"{prefix}_lmer.csv", index=False)
        n_files += 1

        # ---- 6. Satterthwaite denominator df (gene x columns) ----
        satt_data = {"gene": genes}
        for i, coef_name in enumerate(fit.coef_names):
            r_name = COEF_MAP.get(coef_name, coef_name)
            satt_data[f"df_residual_{r_name}"] = fit.df_resid_test[:, i]

        satt_df = pd.DataFrame(satt_data)
        satt_df.to_csv(f"{prefix}_satterthwaite.csv", index=False)
        n_files += 1

        # ---- 7. eBayes outputs (gene x columns) ----
        ebayes_data = {"gene": genes}

        # Scalars replicated per gene (matches R's structure)
        ebayes_data["s2_prior"] = np.full(len(genes), fit_eb.s2_prior)
        ebayes_data["df_prior"] = np.full(len(genes), fit_eb.df_prior)

        # Per-gene vectors
        ebayes_data["s2_post"] = fit_eb.s2_post

        for i, coef_name in enumerate(fit_eb.coef_names):
            r_name = COEF_MAP.get(coef_name, coef_name)
            ebayes_data[f"df_total_{r_name}"] = fit_eb.df_total[:, i]
            ebayes_data[f"t_{r_name}"] = fit_eb.t[:, i]
            ebayes_data[f"p_{r_name}"] = fit_eb.p_value[:, i]
            ebayes_data[f"b_{r_name}"] = fit_eb.lods[:, i]

            # Adjusted p-values (BH)
            pvals = fit_eb.p_value[:, i].copy()
            finite_mask = np.isfinite(pvals)
            adj_p = np.full_like(pvals, np.nan)
            if finite_mask.any():
                adj_p[finite_mask] = false_discovery_control(
                    pvals[finite_mask], method="bh"
                )
            ebayes_data[f"adj_p_{r_name}"] = adj_p

        ebayes_df = pd.DataFrame(ebayes_data)
        ebayes_df.to_csv(f"{prefix}_ebayes.csv", index=False)
        n_files += 1

        print(f"  {assay_name}: saved {n_files} _py_ CSV files to {ref_dir}")

    except Exception as e:
        print(f"  WARNING: {assay_name}: failed to save _py_ outputs: {e}")

